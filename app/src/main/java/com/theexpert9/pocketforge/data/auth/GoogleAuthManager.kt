data class GoogleProfileState(
    val isSignedIn: Boolean = false,
    val uid: String? = null,
    val displayName: String? = null,
    val email: String? = null,
    val photoUrl: String? = null,
    val isAuthenticating: Boolean = false,
    val authError: String? = null
) {
    companion object {
        fun fromFirebaseUser(
            user: FirebaseUser?,
            fallbackDisplayName: String? = null,
            fallbackEmail: String? = null,
            fallbackPhotoUrl: String? = null
        ): GoogleProfileState {
            if (user == null) return GoogleProfileState()
            val resolvedEmail = user.email?.takeIf { it.isNotBlank() } ?: fallbackEmail
            val resolvedName = user.displayName?.takeIf { it.isNotBlank() }
                ?: fallbackDisplayName?.takeIf { it.isNotBlank() }
                ?: resolvedEmail?.substringBefore('@')
                ?: "Google User"
            return GoogleProfileState(
                isSignedIn = true,
                uid = user.uid,
                displayName = resolvedName,
                email = resolvedEmail,
                photoUrl = user.photoUrl?.toString() ?: fallbackPhotoUrl
            )
        }
    }
}

sealed interface GoogleSignInOutcome {
    data class Success(val profile: GoogleProfileState) : GoogleSignInOutcome
    data class Cancelled(val diagnosticHint: String? = null) : GoogleSignInOutcome
    data class Error(val message: String) : GoogleSignInOutcome
}

/**
 * Native in-app Google Sign-In using Jetpack Credential Manager and Firebase Auth.
 * Strictly enforces one credential option per GetCredentialRequest for Android 16 (API 36) safety
 * and resolves default_web_client_id dynamically at runtime so local Termux builds compile cleanly.
 */
object GoogleAuthManager {

    private const val TAG = "Auth"

    fun currentUser(context: Context): FirebaseUser? {
        val app = ensureFirebaseInitialized(context) ?: return null
        return runCatching { Firebase.auth(app).currentUser }.getOrNull()
    }

    fun observeAuthState(context: Context): Flow<FirebaseUser?> = callbackFlow {
        val app = ensureFirebaseInitialized(context)
        if (app == null) {
            trySend(null)
            close()
            return@callbackFlow
        }
        val auth = Firebase.auth(app)
        val listener = FirebaseAuth.AuthStateListener { firebaseAuth ->
            Log.d(TAG, "AuthStateListener fired: user=${firebaseAuth.currentUser?.email ?: "signed_out"}")
            trySend(firebaseAuth.currentUser)
        }
        auth.addAuthStateListener(listener)
        trySend(auth.currentUser)
        awaitClose { auth.removeAuthStateListener(listener) }
    }

    /**
     * Resolves `default_web_client_id` generated by the google-services plugin at runtime
     * without requiring a compile-time `R.string.default_web_client_id` reference.
     */
    private fun resolveWebClientId(context: Context): String? {
        val packages = listOf(context.packageName, BuildConfig.APPLICATION_ID, "com.theexpert9.pocketforge").distinct()
        for (pkg in packages) {
            val resId = context.resources.getIdentifier("default_web_client_id", "string", pkg)
            if (resId != 0) {
                val value = runCatching { context.getString(resId) }.getOrNull()?.trim()
                if (!value.isNullOrBlank()) return value
            }
        }
        return null
    }

    /**
     * Silent startup auto sign-in for previously authorized accounts only (`GetGoogleIdOption`).
     */
    suspend fun attemptAutoSignIn(context: Context): FirebaseUser? {
        val firebaseApp = ensureFirebaseInitialized(context) ?: return null
        val existing = runCatching { Firebase.auth(firebaseApp).currentUser }.getOrNull()
        if (existing != null) return existing

        val clientId = resolveWebClientId(context) ?: return null
        val activity = findActivity(context) ?: return null
        val credentialManager = CredentialManager.create(context)
        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(true)
            .setServerClientId(clientId)
            .setAutoSelectEnabled(true)
            .build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()

        return try {
            val cred = credentialManager.getCredential(activity, request).credential
            if (cred is CustomCredential && cred.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val idToken = GoogleIdTokenCredential.createFrom(cred.data).idToken
                val authResult = Firebase.auth(firebaseApp)
                    .signInWithCredential(GoogleAuthProvider.getCredential(idToken, null))
                    .await()
                authResult.user ?: Firebase.auth(firebaseApp).currentUser
            } else {
                null
            }
        } catch (e: CancellationException) {
            throw e
        } catch (_: NoCredentialException) {
            null
        } catch (e: Exception) {
            Log.d(TAG, "Silent Google auto-sign-in skipped: ${e.message}")
            null
        }
    }

    /**
     * Interactive in-app Google Sign-In bottom sheet (`GetSignInWithGoogleOption`).
     */
    suspend fun signInWithGoogle(context: Context): GoogleSignInOutcome {
        val firebaseApp = ensureFirebaseInitialized(context)
            ?: return GoogleSignInOutcome.Error("Firebase is not initialized in this build.")

        val clientId = resolveWebClientId(context)
        if (clientId.isNullOrBlank()) {
            Log.e(TAG, "Google Sign-In failed: default_web_client_id string resource not found.")
            return GoogleSignInOutcome.Error(
                "Google Sign-In configuration missing: default_web_client_id not found. Ensure app/google-services.json is included in the build."
            )
        }

        val activity = findActivity(context)
            ?: return GoogleSignInOutcome.Error("Cannot launch Google Sign-In outside an Activity context.")

        Log.d(
            TAG,
            "Starting interactive Google Sign-In (pkg=${context.packageName}, clientId=${clientId.take(12)}...${clientId.takeLast(10)})"
        )

        val credentialManager = CredentialManager.create(context)
        val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = clientId).build()
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(signInOption)
            .build()

        return try {
            val result = credentialManager.getCredential(activity, request)
            val credential = result.credential
            Log.d(TAG, "CredentialManager returned credential type=${credential.type}")

            if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                val googleCred = GoogleIdTokenCredential.createFrom(credential.data)
                Log.d(TAG, "Google ID token received for account=${googleCred.id}; exchanging with Firebase Auth…")

                val firebaseAuth = Firebase.auth(firebaseApp)
                val authResult = firebaseAuth
                    .signInWithCredential(GoogleAuthProvider.getCredential(googleCred.idToken, null))
                    .await()

                val signedInUser = authResult.user ?: firebaseAuth.currentUser
                if (signedInUser != null) {
                    Log.d(TAG, "Firebase Auth sign-in succeeded: uid=${signedInUser.uid}, email=${signedInUser.email}")
                    val profile = GoogleProfileState.fromFirebaseUser(
                        user = signedInUser,
                        fallbackDisplayName = googleCred.displayName,
                        fallbackEmail = googleCred.id,
                        fallbackPhotoUrl = googleCred.profilePictureUri?.toString()
                    )
                    GoogleSignInOutcome.Success(profile)
                } else {
                    Log.e(TAG, "Firebase Auth signInWithCredential completed but currentUser is null.")
                    GoogleSignInOutcome.Error("Google verified your account, but Firebase Auth returned no active user.")
                }
            } else {
                Log.e(TAG, "Unexpected credential type: ${credential.type}")
                GoogleSignInOutcome.Error("Unexpected credential type returned (${credential.type}).")
            }
        } catch (e: GetCredentialCancellationException) {
            val rawDetail = e.errorMessage?.toString() ?: e.message.orEmpty()
            Log.w(TAG, "Google Sign-In cancelled/aborted (type=${e.type}): $rawDetail", e)
            val lower = rawDetail.lowercase()
            val looksLikePlayServicesAuthError = lower.contains("16") ||
                lower.contains("reauth") ||
                lower.contains("developer") ||
                lower.contains("28444") ||
                lower.contains("caller") ||
                lower.contains("sha") ||
                lower.contains("client")
            if (looksLikePlayServicesAuthError) {
                GoogleSignInOutcome.Error(
                    "Google Play Services rejected sign-in after account selection ($rawDetail). " +
                        "Add your APK signing keystore SHA-1 to Firebase Console -> Project Settings -> Android app, then re-download google-services.json."
                )
            } else {
                GoogleSignInOutcome.Cancelled(
                    diagnosticHint = "Sign-in did not finish. If you tapped an account and the sheet closed without signing in, " +
                        "add your local Termux/APK keystore SHA-1 in Firebase Console and check Configure > System & Logcat (tag: Auth)."
                )
            }
        } catch (e: GetCredentialException) {
            val detail = e.errorMessage?.toString() ?: e.localizedMessage ?: e.type
            Log.e(TAG, "CredentialManager error (type=${e.type}): $detail", e)
            GoogleSignInOutcome.Error(
                "Google Sign-In failed ($detail). If building locally in Termux, verify your signing keystore SHA-1 is registered in Firebase Console."
            )
        } catch (e: FirebaseAuthException) {
            Log.e(TAG, "FirebaseAuthException (code=${e.errorCode}): ${e.message}", e)
            GoogleSignInOutcome.Error("Firebase Auth rejected Google token [${e.errorCode}]: ${e.localizedMessage}")
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Log.e(TAG, "Google Sign-In failed unexpectedly", e)
            GoogleSignInOutcome.Error(e.localizedMessage ?: "Google Sign-In failed (${e.javaClass.simpleName}).")
        }
    }

    /**
     * Clears Credential Manager state and signs out of Firebase Auth inside NonCancellable.
     */
    suspend fun signOut(context: Context) {
        withContext(NonCancellable) {
            val credentialManager = CredentialManager.create(context)
            try {
                credentialManager.clearCredentialState(ClearCredentialStateRequest())
            } catch (e: Exception) {
                Log.w(TAG, "Failed to clear credential state: ${e.message}")
            } finally {
                runCatching {
                    val app = ensureFirebaseInitialized(context)
                    if (app != null) {
                        Firebase.auth(app).signOut()
                    }
                }
            }
        }
    }

    private fun findActivity(context: Context): Activity? {
        var current: Context? = context
        while (current is ContextWrapper) {
            if (current is Activity) return current
            current = current.baseContext
        }
        return current as? Activity
    }
}
